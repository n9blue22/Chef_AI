do $$
declare unmatched int;
begin
  select count(*) into unmatched from label_fix f
  where not exists (select 1 from public.recipes r where r.id = f.recipe_id and r.title = f.title)
     or not exists (select 1 from public.allergens a where a.slug = f.slug);
  if unmatched > 0 then raise exception 'label_fix: % dòng không khớp id+title hoặc slug — huỷ', unmatched; end if;
  if (select count(*) from public.ingredients where name_vi = 'Dầu hào') <> 1 then
    raise exception 'Không thấy đúng 1 nguyên liệu Dầu hào — huỷ';
  end if;
end $$;

-- (b) nhãn nguyên liệu: Dầu hào + lúa mì + đậu nành (khớp data/ingredient_allergens.csv)
insert into public.ingredient_allergens (ingredient_id, allergen_id)
select i.id, a.id from public.ingredients i join public.allergens a on a.slug in ('wheat', 'soy')
where i.name_vi = 'Dầu hào'
on conflict do nothing;

-- (a)(b)(c) nhãn món
insert into public.recipe_allergens (recipe_id, allergen_id)
select f.recipe_id, a.id from label_fix f join public.allergens a on a.slug = f.slug
on conflict do nothing;

